# build.ps1 - Double Pendulum Phase Space -> dynamical-systems atlas
#
# Toolchain: C:\MinGW (GCC 6.3, gfortran, windres, objdump, Tcl/Tk 8.6).
# Deliverable: dist/dp-phase/ (portable folder) + dist/dp-phase-1.14.0.zip.
# Tcl/Tk is dynamically linked and shipped in the folder; no extraction at runtime.
#
#   .\build.ps1              build + self-test
#   .\build.ps1 -Clean       wipe build/ and dist/ first
#   .\build.ps1 -NoTest      skip self-tests
#   .\build.ps1 -NoGpuTest   skip the GPU compute check
param(
    [switch]$Clean,
    [switch]$NoTest,
    [switch]$NoGpuTest
)
$ErrorActionPreference = 'Continue'
$root = Split-Path -Parent $MyInvocation.MyCommand.Definition
Set-Location $root

$mingw = if ($env:MINGW_ROOT) { $env:MINGW_ROOT } else { 'C:\MinGW' }
$cc  = Join-Path $mingw 'bin\gcc.exe'
$fc  = Join-Path $mingw 'bin\gfortran.exe'
$rc  = Join-Path $mingw 'bin\windres.exe'
$od  = Join-Path $mingw 'bin\objdump.exe'

foreach ($tool in @($cc, $fc, $rc, $od)) {
    if (-not (Test-Path $tool)) { throw "missing tool: $tool" }
}

$build = Join-Path $root 'build'
$obj   = Join-Path $build 'obj'
$gen   = Join-Path $build 'gen'
$dist  = Join-Path $root 'dist'
$stage = Join-Path $dist 'dp-phase'

if ($Clean) {
    Remove-Item -Recurse -Force $build, $dist -ErrorAction SilentlyContinue
}
New-Item -ItemType Directory -Force -Path $obj, $gen, $dist | Out-Null
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory -Force -Path $stage | Out-Null

function Invoke-Tool {
    param([string]$Exe, [string[]]$Arguments, [string]$What)
    $text = & $Exe @Arguments 2>&1 | Out-String
    if ($LASTEXITCODE -ne 0) {
        Write-Host $text
        throw "$What failed (exit $LASTEXITCODE)"
    }
    if ($text.Trim().Length -gt 0) { Write-Host $text.Trim() }
}

function Escape-Shader {
    param([string]$Path)
    $crlf = [string][char]13 + [string][char]10
    $lf   = [string][char]10
    $t = [IO.File]::ReadAllText($Path)
    $t = $t.Replace($crlf, $lf)
    $t = $t.Replace('\', '\\')
    $t = $t.Replace('"', '\"')
    $t = $t.Replace($lf, '\n')
    return $t
}

Write-Host '=== Dynamical Systems Atlas ==='
Write-Host ("toolchain: " + $mingw)

Write-Host '[1/6] checking Tcl/Tk runtime'
$tclDll = Join-Path $mingw 'bin\tcl86.dll'
$tkDll  = Join-Path $mingw 'bin\tk86.dll'
$gccDll = Join-Path $mingw 'bin\libgcc_s_dw2-1.dll'
$zlibDll= Join-Path $mingw 'bin\zlib1.dll'
$tclLib = Join-Path $mingw 'lib\tcl8.6'
$tkLib  = Join-Path $mingw 'lib\tk8.6'
foreach ($path in @($tclDll, $tkDll, $gccDll, $zlibDll, $tclLib, $tkLib)) {
    if (-not (Test-Path $path)) { throw "missing Tcl/Tk component: $path" }
}
Write-Host '      tcl86.dll / tk86.dll / libgcc_s_dw2-1.dll / zlib1.dll'

Write-Host '[2/6] embedding shaders'
$fieldSrc = Escape-Shader (Join-Path $root 'shaders\field.comp')
$vertSrc  = Escape-Shader (Join-Path $root 'shaders\display.vert')
$fragSrc  = Escape-Shader (Join-Path $root 'shaders\display.frag')
$lineVSrc = Escape-Shader (Join-Path $root 'shaders\line.vert')
$lineFSrc = Escape-Shader (Join-Path $root 'shaders\line.frag')
$atlasSrc = Escape-Shader (Join-Path $root 'shaders\atlas.frag')
$genLines = @(
    '/* generated by build.ps1 from shaders/ - do not edit */',
    '#ifndef DP_SHADERS_GEN_H',
    '#define DP_SHADERS_GEN_H',
    ('static const char *DP_SHADER_FIELD = "' + $fieldSrc + '";'),
    ('static const char *DP_SHADER_VERT  = "' + $vertSrc + '";'),
    ('static const char *DP_SHADER_FRAG  = "' + $fragSrc + '";'),
    ('static const char *DP_SHADER_LINE_VERT = "' + $lineVSrc + '";'),
    ('static const char *DP_SHADER_LINE_FRAG = "' + $lineFSrc + '";'),
    ('static const char *DP_SHADER_ATLAS_FRAG = "' + $atlasSrc + '";'),
    '#endif',
    ''
)
$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllLines((Join-Path $gen 'shaders_gen.h'), $genLines, $utf8)
Write-Host ("      field.comp {0:N0} B, display {1:N0} B" -f $fieldSrc.Length, ($vertSrc.Length + $fragSrc.Length))

Write-Host '[3/6] compiling C skeleton'
$cflags = @(
    '-std=gnu99', '-O2', '-Wall', '-Wextra', '-Wno-unused-parameter',
    '-fno-strict-aliasing', '-ffunction-sections', '-fdata-sections',
    '-D_WIN32_WINNT=0x0601', '-DWIN32_LEAN_AND_MEAN',
    '-I', 'src', '-I', 'build\gen'
)
$sources = @(
    'main.c', 'app.c', 'platform.c', 'experiment.c', 'atlas.c', 'model.c', 'model_dp.c', 'model_logistic.c', 'model_henon.c', 'expr.c', 'model_custom.c', 'model_glsl.c', 'session.c', 'sim.c', 'physics.c', 'pool.c',
    'kernel_fortran.c', 'lua_hot.c', 'gpu.c', 'phase_view.c', 'pendulum_view.c', 'panel.c', 'bmp.c', 'png.c', 'selftest.c'
)
$objects = @()
foreach ($s in $sources) {
    $o = Join-Path $obj ($s -replace '\.c$', '.o')
    Invoke-Tool $cc ($cflags + @('-c', (Join-Path 'src' $s), '-o', $o)) "compile $s"
    $objects += $o
}
Write-Host ("      {0} C objects" -f $objects.Count)

Write-Host '[4/6] compiling Fortran kernel'
$fflags = @(
    '-O3', '-finline-limit=4000', '-funroll-loops', '-ftree-vectorize',
    '-msse2', '-mfpmath=sse', '-fno-math-errno', '-ffree-line-length-none',
    '-ffunction-sections', '-fdata-sections', '-J', $obj, '-c'
)
$fobj = Join-Path $obj 'kernel_fortran_f.o'
Invoke-Tool $fc ($fflags + @('fortran\kernel.f90', '-o', $fobj)) 'compile kernel.f90'
$objects += $fobj

Write-Host '[5/6] compiling resources'
$robj = Join-Path $obj 'app_res.o'
Invoke-Tool $rc @('-c', '65001', '-I', $root, '-I', (Join-Path $root 'src\res'),
                  '-i', (Join-Path $root 'src\res\app.rc'), '-o', $robj) 'windres'
$objects += $robj

Write-Host '[6/6] linking (dynamic Tcl/Tk, static C/Fortran)'
$exe = Join-Path $stage 'dp-phase.exe'
$lflags = @(
    '-mwindows', '-static', '-static-libgcc', '-static-libgfortran',
    '-Wl,--gc-sections', '-Wl,--enable-stdcall-fixup', '-s',
    '-lopengl32', '-lgdi32', '-luser32', '-lwinmm', '-lcomdlg32', '-llua', '-lz', '-lm',
    '-ltk86', '-ltcl86'
)
Invoke-Tool $fc ($objects + @('-o', $exe) + $lflags) 'link'

$size = (Get-Item $exe).Length
Write-Host ("OK -> {0}  ({1:N0} bytes)" -f $exe, $size)

Write-Host ''
Write-Host '--- staging portable folder ---'
Copy-Item $tclDll  $stage -Force
Copy-Item $tkDll   $stage -Force
Copy-Item $gccDll  $stage -Force
Copy-Item $zlibDll $stage -Force
$stageLib = Join-Path $stage 'lib'
New-Item -ItemType Directory -Force -Path (Join-Path $stageLib 'tcl8.6') | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $stageLib 'tk8.6') | Out-Null
Copy-Item (Join-Path $tclLib '*') (Join-Path $stageLib 'tcl8.6') -Recurse -Force
Copy-Item (Join-Path $tkLib '*')  (Join-Path $stageLib 'tk8.6')  -Recurse -Force
$stageUi = Join-Path $stage 'ui'
New-Item -ItemType Directory -Force -Path $stageUi | Out-Null
Copy-Item (Join-Path $root 'ui\panel.tcl') $stageUi -Force
$stageExp = Join-Path $stage 'experiments'
New-Item -ItemType Directory -Force -Path $stageExp | Out-Null
Copy-Item (Join-Path $root 'experiments\experiment.lua') (Join-Path $stageExp 'experiment.lua') -Force
Copy-Item (Join-Path $root 'README.md') $stage -Force -ErrorAction SilentlyContinue
Copy-Item (Join-Path $root 'docs') (Join-Path $stage 'docs') -Recurse -Force -ErrorAction SilentlyContinue
Write-Host ("      staged {0:N1} MB" -f ((Get-ChildItem $stage -Recurse -File | Measure-Object Length -Sum).Sum / 1MB))

$zip = Join-Path $dist 'dp-phase-1.14.0.zip'
Remove-Item $zip -Force -ErrorAction SilentlyContinue
Compress-Archive -Path $stage -DestinationPath $zip -CompressionLevel Optimal
Write-Host ("      {0}  ({1:N1} MB)" -f $zip, ((Get-Item $zip).Length / 1MB))

Write-Host ''
Write-Host '--- import table audit ---'
$imports = & $od -p $exe | Select-String 'DLL Name:' | ForEach-Object {
    ($_ -split 'DLL Name:')[1].Trim()
} | Sort-Object -Unique
$allowed = @('kernel32.dll', 'user32.dll', 'gdi32.dll', 'opengl32.dll', 'winmm.dll', 'msvcrt.dll', 'tcl86.dll', 'tk86.dll', 'comdlg32.dll')
$badImports = $false
foreach ($dll in $imports) {
    $low = $dll.ToLower()
    if ($allowed -contains $low) { Write-Host ("  [ok]   {0}" -f $dll) }
    else { Write-Host ("  [BAD]  {0}" -f $dll); $badImports = $true }
}
if ($badImports) { throw 'unexpected DLL import detected' }

if (-not $NoTest) {
    Write-Host ''
    Write-Host '--- selftest ---'
    $out = & $exe /selftest 2>&1 | Out-String
    Write-Host $out.TrimEnd()
    if ($LASTEXITCODE -ne 0) { throw "selftest failed (exit $LASTEXITCODE)" }

    if (-not $NoGpuTest) {
        Write-Host ''
        Write-Host '--- gpu selftest ---'
        $gout = & $exe /gpu-selftest 2>&1 | Out-String
        Write-Host $gout.TrimEnd()
        if ($LASTEXITCODE -ne 0) {
            Write-Warning 'GPU compute self-test did not pass; the CPU fallback is still usable.'
        }
    }
}

Write-Host ''
Write-Host 'build complete.'